"""Stage 5 — `./tasks.ps1 intelligence` / `make intelligence` / `python -m pratirakshak.intelligence`."""

from __future__ import annotations

import sys
from typing import Any

from pratirakshak.ingest.cmapss import HEADLINE_SENSORS, SENSOR_NAMES
from pratirakshak.intelligence.explain import build_explanations
from pratirakshak.intelligence.graph import build_graph
from pratirakshak.intelligence.harness import run_all
from pratirakshak.intelligence.mission import mission_fit
from pratirakshak.io import write_json, write_parquet, write_text
from pratirakshak.settings import MODELS_DIR, PROCESSED_DIR, REPORTS_DIR

STATE = PROCESSED_DIR / "state"


def harness_report(sys_r: dict[str, Any], eng_r: dict[str, Any]) -> str:
    L = ["# Sensor trust — fault-injection harness", "",
         "_Generated by `python -m pratirakshak.intelligence`. Faults are injected with known onset/end (ground truth); "
         "a fault counts as detected if trust < 60 at any step between onset and 3 steps after it ends. A false alarm is "
         "trust < 60 on a sensor whose whole scoring window was fault-free._", "",
         "| Domain | Fault episodes | Detection rate | Median delay | False-alarm rate (per sensor-step) |", "|---|---|---|---|---|",
         f"| Synthetic systems `SIMULATED` (daily) | {sys_r['episodes']} | {sys_r['detection_rate']:.1%} | "
         f"{sys_r['median_delay_steps']} days | {sys_r['false_alarm_rate_per_sensor_step']:.2%} |",
         f"| Engines `REAL` signals + injected faults (per cycle) | {eng_r['episodes']} | {eng_r['detection_rate']:.1%} | "
         f"{eng_r['median_delay_cycles']} cycles | {eng_r['false_alarm_rate_per_sensor_step']:.2%} |", "",
         "| Fault type | Systems episodes | Systems detected | Engine episodes | Engine detected |", "|---|---|---|---|---|"]
    for t in ("stuck", "drift", "dropout", "spike"):
        a, b = sys_r["by_type"].get(t, {}), eng_r["by_type"].get(t, {})
        L.append(f"| {t} | {a.get('episodes', 0)} | {a.get('detection_rate', 0):.1%} | {b.get('episodes', 0)} | "
                 f"{b.get('detection_rate', 0):.1%} |")
    L += ["", "Where it is weak: short dropouts (a few missing days barely lower trust) and slow drifts that stay inside the "
          "sibling-residual tolerance for most of their episode. Engine episodes are few (43), so treat that rate as indicative."]
    return "\n".join(L) + "\n"


def main() -> int:
    print("fitting trust relations + fault-injection harness …")
    r = run_all()
    s, e = r["systems"], r["engines"]
    print(f"  systems: {s['episodes']} faults · detection {s['detection_rate']:.1%} · median delay {s['median_delay_steps']} d · "
          f"false alarms {s['false_alarm_rate_per_sensor_step']:.2%} per sensor-day")
    print(f"  engines: {e['episodes']} faults · detection {e['detection_rate']:.1%} · median delay {e['median_delay_cycles']} cycles · "
          f"false alarms {e['false_alarm_rate_per_sensor_step']:.2%} per sensor-cycle")
    print("  by type (systems):", {k: f"{v['detection_rate']:.0%} of {v['episodes']}" for k, v in s["by_type"].items()})
    write_text(REPORTS_DIR / "trust_harness.md", harness_report(s, e))
    write_json(MODELS_DIR / "intelligence" / "trust_harness.json", {"systems": s, "engines": e})
    write_json(MODELS_DIR / "intelligence" / "trust_relations.json", r["relations"])
    fleet = r["fleet"]
    write_parquet(STATE / "trust_d0.parquet", fleet)
    print(f"  fleet at D+0: {len(fleet)} sensors scored, {int((fleet['trust'] < 60).sum())} untrusted")

    print("explanations …")
    ex = build_explanations(fleet)
    write_json(STATE / "explanations.json", ex)
    eng_sensors = {d["sensor"] for t in ex.values() for d in t["engines"]["drivers"]}
    assert eng_sensors <= set(HEADLINE_SENSORS), f"non-headline engine sensor in explanations: {eng_sensors - set(HEADLINE_SENSORS)}"
    for t in ex.values():
        for d in t["engines"]["drivers"]:
            assert SENSOR_NAMES[d["sensor"]][1].lower() in d["text"].lower(), d["text"]
    levels = [v["confidence"]["level"] for t in ex.values() for v in t.values()]
    print(f"  engine driver sensors used: {sorted(SENSOR_NAMES[x][0] for x in eng_sensors)} (all headline: True)")
    print("  confidence levels:", {k: levels.count(k) for k in ("high", "medium", "low")})
    sample_tail = next(iter(ex))
    print(f"  e.g. {sample_tail} engines:", " | ".join(d["text"] for d in ex[sample_tail]["engines"]["drivers"]))

    print("mission fit …")
    mf = mission_fit()
    write_json(STATE / "mission_fit.json", mf)
    for m in mf:
        print(f"  {m['id']}: assigned {m['assigned']} (shortfall {m['shortfall']}); excluded "
              f"{sum(c['excluded'] for c in m['candidates'])}/{len(m['candidates'])}")

    g = build_graph()
    write_json(MODELS_DIR / "intelligence" / "graph.json", g)
    top = [n["label"] for n in g["nodes"] if n["kind"] == "sensor" and n.get("system") == "engines"][:5]
    print(f"graph: {len(g['nodes'])} nodes, {len(g['edges'])} edges; top engine sensors {top}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
