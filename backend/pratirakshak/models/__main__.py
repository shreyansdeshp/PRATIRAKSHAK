"""Stage 3 — `./tasks.ps1 train [-Fast]` / `make train [FAST=1]` / `python -m pratirakshak.models [--fast] [--subsets FD001 ...]`."""

from __future__ import annotations

import argparse
import sys
from typing import Any

from pratirakshak.ingest.cmapss import SUBSETS
from pratirakshak.io import write_json, write_text
from pratirakshak.models.engine import run_subset
from pratirakshak.settings import MODELS_DIR, REPORTS_DIR

MODEL_LABEL = {"ridge": "Baseline A · Ridge", "lgbm": "Baseline B · LightGBM", "main": "Main · CNN-GRU quantile"}


def table(results: list[dict[str, Any]]) -> list[str]:
    rows = ["| Subset | Model | RMSE | RMSE (capped) | MAE | NASA score | PICP 80 % | MPIW 80 % | Serving |",
            "|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        for m in ("ridge", "lgbm", "main"):
            mt = r["metrics"][m]
            iv = r["headline_interval"].get(m)
            picp = "" if iv is None else f"{iv['empirical']:.3f}"
            mpiw = "" if iv is None else f"{iv['mean_width']:.1f}"
            serving = "**yes**" if r["serving_model"] == m else ""
            rows.append(
                f"| {r['subset']} | {MODEL_LABEL[m]} | {mt['rmse']:.2f} | {mt['rmse_capped']:.2f} | {mt['mae']:.2f} | "
                f"{mt['nasa_score']:.0f} | {picp} | {mpiw} | {serving} |")
    return rows


def subset_report(r: dict[str, Any]) -> str:
    L = [f"# Engine RUL — {r['subset']}  `REAL`", "",
         "_Generated by `python -m pratirakshak.models`. Official test set, last window per engine. "
         "RMSE is against the true RUL from `RUL_{s}.txt`; \"capped\" compares with min(true, 125)._".replace("{s}", r["subset"]),
         "", *table([r]), "",
         f"Serving model: **{MODEL_LABEL[r['serving_model']]}** (main-vs-LightGBM RMSE gain {r['main_vs_lgbm_rmse_gain']:+.1%}; "
         "rule: main serves only if ≥ 3 % better).", "",
         "## Calibration (split conformal on validation-unit truncation windows; test coverage vs capped truth)", "",
         "| Nominal | Main empirical | Main width | LightGBM empirical | LightGBM width |", "|---|---|---|---|---|"]
    for a, b in zip(r["intervals"]["main"], r["intervals"]["lgbm"], strict=True):
        L.append(f"| {a['nominal']:.0%} | {a['empirical']:.3f} | {a['mean_width']:.1f} | {b['empirical']:.3f} | {b['mean_width']:.1f} |")
    ra = r["alarm_replay"]
    L += ["", f"## Alarm quality (P(RUL ≤ {ra['horizon']}) ≥ θ = {ra['theta']}, serving model)", "",
          f"- Replay engines (held out from fitting and calibration, run to failure): {ra['units']} engines, "
          f"missed {ra['missed']}, premature (> {3 * ra['horizon']} cycles early) {ra['premature_gt_3H']}; "
          f"lead time p10 / median / p90 = {ra['lead_p10']} / {ra['lead_median']} / {ra['lead_p90']} cycles.",
          "- Test engines, one snapshot each (event = true RUL ≤ H):", "",
          "| θ | False-alarm rate | Miss rate |", "|---|---|---|"]
    L += [f"| {x['theta']} | {x['false_alarm_rate']:.3f} | {x['miss_rate']:.3f} |" for x in r["alarm_test_roc"]]
    L += ["", f"Ensemble disagreement (std of member medians, mean over test engines): {r['ensemble_disagreement_mean']} cycles.",
          f"Fast mode: {r['fast']}.", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fast", action="store_true")
    ap.add_argument("--subsets", nargs="*", default=list(SUBSETS))
    args = ap.parse_args()

    results = []
    for s in args.subsets:
        r = run_subset(s, args.fast)
        print(f"  {s}: serving={r['serving_model']} · {r['seconds']} s")
        results.append(r)
        write_text(REPORTS_DIR / f"engine_{s}.md", subset_report(r))

    if set(args.subsets) == set(SUBSETS):
        summary = ["# Engine RUL — all subsets  `REAL`", "",
                   "_One training run, default settings (SPEC §0 rule 15). Generated; do not edit._", "", *table(results), ""]
        bad = [r["subset"] for r in results if not 0.75 <= r["headline_interval"][r["serving_model"]]["empirical"] <= 0.85]
        summary.append("80 % interval coverage within 75–85 % for every subset." if not bad
                       else f"**Coverage outside 75–85 % for {', '.join(bad)}**: flagged, not hidden (see per-subset reports).")
        write_text(REPORTS_DIR / "engine_summary.md", "\n".join(summary) + "\n")
        write_json(MODELS_DIR / "engine" / "summary.json", [{k: v for k, v in r.items() if k != "seconds"} for r in results])
    print("\n" + "\n".join(table(results)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
